'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname,'..');
const calls=[];
const auth={access_token:'test-token',refresh_token:'test-refresh',expires_at:9999999999,user:{id:'owner-test',email:'store@example.com'}};
const ls={ 'lc-owner-auth-session-v1':JSON.stringify(auth) };
const localStorage={getItem:key=>ls[key]??null,setItem:(key,val)=>ls[key]=val,removeItem:key=>delete ls[key]};
const window={LC_BACKEND_CONFIG:{url:'https://test.supabase.co',publishableKey:'sb_publishable_test'}};
const fetch=async (url,opts)=>{
  calls.push({url,opts});
  let body=[];
  if(url.endsWith('/rpc/lc_sales_summary'))body=[{paid_orders:2,paid_total_cents:14000,partially_refunded_orders:1,refunded_orders:0}];
  return {ok:true,status:200,text:async()=>JSON.stringify(body)};
};
vm.runInNewContext(fs.readFileSync(path.join(root,'live-client.js'),'utf8'),{window,localStorage,fetch,Date,JSON,Blob});
(async()=>{
  const api=window.LCBackend;
  const start='2026-10-01T00:00:00.000Z',end='2026-11-01T00:00:00.000Z';
  const r=await api.readSalesSummary(start,end);
  assert.equal(r.paid_total_cents,14000);
  assert.equal(r.paid_orders,2);
  let c=calls.find(x=>x.url.includes('/rpc/lc_sales_summary'));
  assert.equal(c.opts.headers.Authorization,'Bearer test-token');
  assert.deepEqual(JSON.parse(c.opts.body),{start_utc:start,end_utc:end});
  await api.markInternalAccount('team-member-uuid');
  c=calls.find(x=>x.url.includes('/rpc/lc_mark_internal_account'));
  assert.equal(c.opts.headers.Authorization,'Bearer test-token');
  assert.equal(JSON.parse(c.opts.body).target_user_id,'team-member-uuid');
  const ui=fs.readFileSync(path.join(root,'admin.js'),'utf8');
  assert.match(ui,/Last 7 days/);
  assert.match(ui,/Choose dates/);
  assert.match(ui,/Paid order total/);
  const signup=fs.readFileSync(path.join(root,'customer-auth.js'),'utf8');
  assert.match(signup,/account_type: 'customer'/);
  const sql=fs.readFileSync(path.join(root,'supabase/005_revenue_internal_customers.sql'),'utf8');
  assert.match(sql,/not exists\(select 1 from public\.lc_store_members/);
  assert.match(sql,/not exists\(select 1 from public\.lc_internal_accounts/);
  const legal=fs.readFileSync(path.join(root,'policy.js'),'utf8');
  assert.match(legal,/No optional tracking categories are active/);
  console.log('Revenue, owner-only API requests, customer categorization and privacy checks passed');
})().catch(error=>{console.error(error);process.exitCode=1});
